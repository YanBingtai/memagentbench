//! An independent, retrieval-based just-in-time reinforcement learning scorer.
//!
//! The crate intentionally owns its contracts. It does not depend on the
//! memory-agent predictor/retrieval pipeline or on the runtime admission
//! layer. A caller records completed trajectories, supplies a state vector at
//! decision time, and receives an action recommendation plus an optional
//! correction for an observed action.
//!
//! This is a non-parametric JitRL baseline: it estimates action values from
//! similar historical transitions. It does not claim to train a neural policy
//! or to replace a provider-specific memory method.

use std::{
    cmp::Ordering,
    collections::{BTreeMap, VecDeque},
};

use serde::{Deserialize, Serialize};
use thiserror::Error;
use uuid::Uuid;

/// One state/action/reward observation in a completed or partial trajectory.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Transition {
    pub id: Uuid,
    /// A fixed-dimensional representation generated by the caller.
    pub state: Vec<f32>,
    pub action: String,
    pub reward: f32,
    pub terminal: bool,
    pub timestamp_ms: u64,
}

impl Transition {
    /// Creates a validated transition. `state` must be finite and non-empty.
    pub fn new(
        state: Vec<f32>,
        action: impl Into<String>,
        reward: f32,
        terminal: bool,
        timestamp_ms: u64,
    ) -> Result<Self, StoreError> {
        let action = action.into();
        validate_state(&state)?;
        if action.trim().is_empty() {
            return Err(StoreError::EmptyAction);
        }
        if !reward.is_finite() {
            return Err(StoreError::NonFiniteReward);
        }
        Ok(Self {
            id: Uuid::new_v4(),
            state,
            action,
            reward,
            terminal,
            timestamp_ms,
        })
    }
}

/// A sequence of transitions belonging to one episode or task run.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Trajectory {
    pub id: Uuid,
    pub run_id: Option<String>,
    pub transitions: Vec<Transition>,
}

impl Trajectory {
    pub fn new(transitions: Vec<Transition>, run_id: Option<String>) -> Result<Self, StoreError> {
        validate_trajectory(&transitions)?;
        Ok(Self {
            id: Uuid::new_v4(),
            run_id,
            transitions,
        })
    }

    pub fn state_dimension(&self) -> usize {
        self.transitions
            .first()
            .map_or(0, |transition| transition.state.len())
    }
}

/// A nearest historical transition returned by the similarity index.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Neighbor {
    pub trajectory_id: Uuid,
    pub transition_id: Uuid,
    pub transition_index: usize,
    pub action: String,
    pub reward: f32,
    /// Cosine similarity in [-1, 1], clamped to finite values.
    pub similarity: f32,
}

/// A bounded in-memory trajectory repository and brute-force similarity index.
///
/// Keeping this component independent makes the JitRL scorer usable with a
/// benchmark fixture first. A persistent implementation can later mirror this
/// API without changing recommendation semantics.
#[derive(Debug, Clone)]
pub struct InMemoryTrajectoryStore {
    capacity: usize,
    trajectories: BTreeMap<Uuid, Trajectory>,
    insertion_order: VecDeque<Uuid>,
    state_dimension: Option<usize>,
}

impl InMemoryTrajectoryStore {
    pub fn new(capacity: usize) -> Result<Self, StoreError> {
        if capacity == 0 {
            return Err(StoreError::InvalidCapacity);
        }
        Ok(Self {
            capacity,
            trajectories: BTreeMap::new(),
            insertion_order: VecDeque::new(),
            state_dimension: None,
        })
    }

    pub fn capacity(&self) -> usize {
        self.capacity
    }

    pub fn len(&self) -> usize {
        self.trajectories.len()
    }

    pub fn is_empty(&self) -> bool {
        self.trajectories.is_empty()
    }

    pub fn get(&self, id: Uuid) -> Option<&Trajectory> {
        self.trajectories.get(&id)
    }

    pub fn iter(&self) -> impl Iterator<Item = &Trajectory> {
        self.trajectories.values()
    }

    /// Inserts a trajectory and evicts the oldest trajectory at capacity.
    pub fn insert(&mut self, trajectory: Trajectory) -> Result<(), StoreError> {
        validate_trajectory(&trajectory.transitions)?;
        let dimension = trajectory.state_dimension();
        if let Some(expected) = self.state_dimension {
            if expected != dimension {
                return Err(StoreError::StateDimensionMismatch {
                    expected,
                    found: dimension,
                });
            }
        }
        if self.trajectories.contains_key(&trajectory.id) {
            self.insertion_order.retain(|id| *id != trajectory.id);
        }
        self.state_dimension = Some(dimension);
        let id = trajectory.id;
        self.trajectories.insert(id, trajectory);
        self.insertion_order.push_back(id);
        while self.trajectories.len() > self.capacity {
            if let Some(evicted) = self.insertion_order.pop_front() {
                self.trajectories.remove(&evicted);
            }
        }
        Ok(())
    }

    /// Returns the nearest transitions using cosine similarity.
    pub fn search(
        &self,
        query: &[f32],
        limit: usize,
        min_similarity: f32,
    ) -> Result<Vec<Neighbor>, SearchError> {
        validate_query(query)?;
        if !(0.0..=1.0).contains(&min_similarity) {
            return Err(SearchError::InvalidSimilarityThreshold);
        }
        if limit == 0 || self.is_empty() {
            return Ok(Vec::new());
        }
        if let Some(expected) = self.state_dimension {
            if expected != query.len() {
                return Err(SearchError::StateDimensionMismatch {
                    expected,
                    found: query.len(),
                });
            }
        }

        let mut neighbors = self
            .trajectories
            .values()
            .flat_map(|trajectory| {
                trajectory
                    .transitions
                    .iter()
                    .enumerate()
                    .filter_map(|(index, transition)| {
                        let similarity = cosine_similarity(query, &transition.state);
                        (similarity.is_finite() && similarity >= min_similarity).then(|| Neighbor {
                            trajectory_id: trajectory.id,
                            transition_id: transition.id,
                            transition_index: index,
                            action: transition.action.clone(),
                            reward: transition.reward,
                            similarity,
                        })
                    })
            })
            .collect::<Vec<_>>();

        neighbors.sort_by(|left, right| {
            right
                .similarity
                .partial_cmp(&left.similarity)
                .unwrap_or(Ordering::Equal)
                .then_with(|| left.trajectory_id.cmp(&right.trajectory_id))
                .then_with(|| left.transition_index.cmp(&right.transition_index))
        });
        neighbors.truncate(limit);
        Ok(neighbors)
    }
}

/// Computes the discounted return from every transition in one trajectory.
/// A terminal transition receives its own reward but does not include rewards
/// from a later episode; the transition immediately before it may still
/// receive the terminal reward as part of the same episode.
pub fn discounted_returns(transitions: &[Transition], gamma: f32) -> Result<Vec<f32>, ReturnError> {
    if transitions.is_empty() {
        return Err(ReturnError::EmptyTrajectory);
    }
    if !gamma.is_finite() || !(0.0..=1.0).contains(&gamma) {
        return Err(ReturnError::InvalidGamma);
    }
    let mut returns = vec![0.0; transitions.len()];
    let mut running = 0.0;
    for (index, transition) in transitions.iter().enumerate().rev() {
        if !transition.reward.is_finite() {
            return Err(ReturnError::NonFiniteReward { index });
        }
        let continuation = if transition.terminal { 0.0 } else { running };
        running = transition.reward + gamma * continuation;
        if !running.is_finite() {
            return Err(ReturnError::NonFiniteReturn { index });
        }
        returns[index] = running;
    }
    Ok(returns)
}

/// Configuration for the retrieval-based JitRL scorer.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct JitRlConfig {
    pub gamma: f32,
    pub top_k: usize,
    pub min_similarity: f32,
    /// Scale applied to normalized historical advantages before they are
    /// added to a model-provided action logit.
    pub advantage_scale: f32,
    pub min_correction_advantage: f32,
    pub min_correction_confidence: f32,
}

impl Default for JitRlConfig {
    fn default() -> Self {
        Self {
            gamma: 0.95,
            top_k: 8,
            min_similarity: 0.2,
            advantage_scale: 1.0,
            min_correction_advantage: 0.1,
            min_correction_confidence: 0.5,
        }
    }
}

impl JitRlConfig {
    pub fn validate(self) -> Result<Self, EngineError> {
        if !self.gamma.is_finite() || !(0.0..=1.0).contains(&self.gamma) {
            return Err(EngineError::InvalidGamma);
        }
        if self.top_k == 0 {
            return Err(EngineError::InvalidTopK);
        }
        if !self.min_similarity.is_finite() || !(0.0..=1.0).contains(&self.min_similarity) {
            return Err(EngineError::InvalidSimilarityThreshold);
        }
        if !self.advantage_scale.is_finite() || self.advantage_scale < 0.0 {
            return Err(EngineError::InvalidAdvantageScale);
        }
        if !self.min_correction_advantage.is_finite() || self.min_correction_advantage < 0.0 {
            return Err(EngineError::InvalidCorrectionThreshold);
        }
        if !self.min_correction_confidence.is_finite()
            || !(0.0..=1.0).contains(&self.min_correction_confidence)
        {
            return Err(EngineError::InvalidCorrectionThreshold);
        }
        Ok(self)
    }
}

/// Value estimate for one action at a queried state.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ActionScore {
    pub action: String,
    pub expected_return: f32,
    pub advantage: f32,
    pub support_count: usize,
    pub mean_similarity: f32,
}

/// The recommendation and its evidence from historical trajectories.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Recommendation {
    pub selected: ActionScore,
    pub alternatives: Vec<ActionScore>,
    pub baseline: f32,
    pub confidence: f32,
    pub neighbors_considered: usize,
}

/// One action candidate produced by the base model before JitRL adjustment.
///
/// `base_logit` is an action-level score supplied by the caller. It is not a
/// token log probability; OpenAI-compatible chat APIs generally do not expose
/// the logits needed for exact token-level modulation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ActionCandidate {
    pub action: String,
    pub base_logit: f32,
}

/// One action after adding JitRL's normalized historical advantage.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AdjustedAction {
    pub action: String,
    pub base_logit: f32,
    pub adjusted_logit: f32,
    pub expected_return: f32,
    pub advantage: f32,
    pub normalized_advantage: f32,
    pub support_count: usize,
    pub mean_similarity: f32,
}

/// Action-level approximation of JitRL's logit correction.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PolicyAdjustment {
    pub selected: AdjustedAction,
    pub alternatives: Vec<AdjustedAction>,
    pub baseline: f32,
    pub confidence: f32,
    pub neighbors_considered: usize,
}

/// A correction decision for an observed action.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CorrectionDecision {
    KeepObserved,
    ReplaceWithRecommendation,
    Abstain,
}

/// Explainable correction output; it does not mutate the trajectory store.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Correction {
    pub observed_action: String,
    pub recommended_action: String,
    pub decision: CorrectionDecision,
    pub advantage_gap: f32,
    pub confidence: f32,
    pub reason: String,
}

/// Retrieval-based JitRL scorer. It owns only its independent trajectory store.
#[derive(Debug, Clone)]
pub struct JitRlEngine {
    config: JitRlConfig,
    store: InMemoryTrajectoryStore,
}

impl JitRlEngine {
    pub fn new(capacity: usize, config: JitRlConfig) -> Result<Self, EngineError> {
        config.validate()?;
        Ok(Self {
            config,
            store: InMemoryTrajectoryStore::new(capacity)?,
        })
    }

    pub fn config(&self) -> JitRlConfig {
        self.config
    }

    pub fn store(&self) -> &InMemoryTrajectoryStore {
        &self.store
    }

    pub fn store_mut(&mut self) -> &mut InMemoryTrajectoryStore {
        &mut self.store
    }

    pub fn record(&mut self, trajectory: Trajectory) -> Result<(), EngineError> {
        self.store.insert(trajectory)?;
        Ok(())
    }

    /// Recommends the action with the highest similarity-weighted advantage.
    pub fn recommend(
        &self,
        state: &[f32],
        allowed_actions: Option<&[String]>,
    ) -> Result<Recommendation, EngineError> {
        let neighbors = self
            .store
            .search(state, self.config.top_k, self.config.min_similarity)?;
        if neighbors.is_empty() {
            return Err(EngineError::NoEvidence);
        }

        let allowed = allowed_actions.map(|actions| {
            actions
                .iter()
                .map(String::as_str)
                .collect::<std::collections::BTreeSet<_>>()
        });
        let mut grouped: BTreeMap<String, ActionAccumulator> = BTreeMap::new();
        let mut baseline_weight = 0.0;
        let mut baseline_sum = 0.0;
        let mut similarity_sum = 0.0;
        let mut usable_neighbors = 0usize;

        for neighbor in neighbors {
            if allowed
                .as_ref()
                .is_some_and(|actions| !actions.contains(neighbor.action.as_str()))
            {
                continue;
            }
            let trajectory = self
                .store
                .get(neighbor.trajectory_id)
                .ok_or(EngineError::MissingTrajectory)?;
            let returns = discounted_returns(&trajectory.transitions, self.config.gamma)?;
            let expected_return = returns
                .get(neighbor.transition_index)
                .copied()
                .ok_or(EngineError::MissingTransition)?;
            let weight = neighbor.similarity.max(0.000_001);
            let entry = grouped.entry(neighbor.action).or_default();
            entry.weighted_return += weight * expected_return;
            entry.weight += weight;
            entry.support_count += 1;
            entry.similarity_sum += neighbor.similarity;
            baseline_sum += weight * expected_return;
            baseline_weight += weight;
            similarity_sum += neighbor.similarity;
            usable_neighbors += 1;
        }

        if grouped.is_empty() {
            return Err(EngineError::NoAllowedAction);
        }
        let baseline = baseline_sum / baseline_weight.max(0.000_001);
        let mut scores = grouped
            .into_iter()
            .map(|(action, aggregate)| {
                let expected_return = aggregate.weighted_return / aggregate.weight.max(0.000_001);
                ActionScore {
                    action,
                    expected_return,
                    advantage: expected_return - baseline,
                    support_count: aggregate.support_count,
                    mean_similarity: aggregate.similarity_sum / aggregate.support_count as f32,
                }
            })
            .collect::<Vec<_>>();
        scores.sort_by(compare_action_scores);
        let selected = scores.first().cloned().ok_or(EngineError::NoEvidence)?;
        let alternatives = scores.into_iter().skip(1).collect();
        let confidence = (similarity_sum / usable_neighbors as f32).clamp(0.0, 1.0);
        Ok(Recommendation {
            selected,
            alternatives,
            baseline,
            confidence,
            neighbors_considered: usable_neighbors,
        })
    }

    /// Adds retrieved advantages to model-provided action-level scores.
    ///
    /// This is the integration point for a caller that has asked an LLM for
    /// several candidate actions. The core crate never calls an LLM and never
    /// assumes that the caller's scores are token logits. Candidates without
    /// historical evidence keep their original score and receive zero
    /// advantage, which makes the fallback deterministic and safe.
    pub fn adjust(
        &self,
        state: &[f32],
        candidates: &[ActionCandidate],
    ) -> Result<PolicyAdjustment, EngineError> {
        validate_candidates(candidates)?;
        let allowed_actions = candidates
            .iter()
            .map(|candidate| candidate.action.clone())
            .collect::<Vec<_>>();
        let recommendation = self.recommend(state, Some(&allowed_actions))?;
        let mut by_action = BTreeMap::new();
        by_action.insert(
            recommendation.selected.action.clone(),
            recommendation.selected.clone(),
        );
        by_action.extend(
            recommendation
                .alternatives
                .iter()
                .cloned()
                .map(|score| (score.action.clone(), score)),
        );

        let max_positive = by_action
            .values()
            .map(|score| score.advantage)
            .filter(|advantage| *advantage > 0.0)
            .fold(0.0_f32, f32::max);
        let max_negative = by_action
            .values()
            .map(|score| score.advantage.abs())
            .fold(0.0_f32, f32::max);

        let mut adjusted = candidates
            .iter()
            .map(|candidate| {
                let score = by_action.get(&candidate.action);
                let advantage = score.map_or(0.0, |value| value.advantage);
                let normalized_advantage = if max_positive > 0.0 {
                    (advantage / max_positive).clamp(-1.0, 1.0)
                } else if max_negative > 0.0 {
                    (advantage / max_negative).clamp(-1.0, 1.0)
                } else {
                    0.0
                };
                AdjustedAction {
                    action: candidate.action.clone(),
                    base_logit: candidate.base_logit,
                    adjusted_logit: candidate.base_logit
                        + self.config.advantage_scale * normalized_advantage,
                    expected_return: score
                        .map_or(recommendation.baseline, |value| value.expected_return),
                    advantage,
                    normalized_advantage,
                    support_count: score.map_or(0, |value| value.support_count),
                    mean_similarity: score.map_or(0.0, |value| value.mean_similarity),
                }
            })
            .collect::<Vec<_>>();
        adjusted.sort_by(compare_adjusted_actions);
        let selected = adjusted.first().cloned().ok_or(EngineError::NoEvidence)?;
        let alternatives = adjusted.into_iter().skip(1).collect();
        Ok(PolicyAdjustment {
            selected,
            alternatives,
            baseline: recommendation.baseline,
            confidence: recommendation.confidence,
            neighbors_considered: recommendation.neighbors_considered,
        })
    }

    /// Compares an observed action with a recommendation without mutating data.
    pub fn correct(
        &self,
        state: &[f32],
        observed_action: &str,
        allowed_actions: Option<&[String]>,
    ) -> Result<Correction, EngineError> {
        if observed_action.trim().is_empty() {
            return Err(EngineError::EmptyObservedAction);
        }
        let recommendation = self.recommend(state, allowed_actions)?;
        if recommendation.selected.action == observed_action {
            return Ok(Correction {
                observed_action: observed_action.to_string(),
                recommended_action: recommendation.selected.action,
                decision: CorrectionDecision::KeepObserved,
                advantage_gap: 0.0,
                confidence: recommendation.confidence,
                reason: "observed action matches the JitRL recommendation".to_string(),
            });
        }
        let observed_value = recommendation
            .alternatives
            .iter()
            .find(|score| score.action == observed_action)
            .map_or(recommendation.baseline, |score| score.expected_return);
        let advantage_gap = recommendation.selected.expected_return - observed_value;
        let confidence = recommendation.confidence;
        let decision = if confidence < self.config.min_correction_confidence {
            CorrectionDecision::Abstain
        } else if advantage_gap >= self.config.min_correction_advantage {
            CorrectionDecision::ReplaceWithRecommendation
        } else {
            CorrectionDecision::Abstain
        };
        let reason = match decision {
            CorrectionDecision::ReplaceWithRecommendation => {
                "recommended action has sufficient estimated advantage".to_string()
            }
            CorrectionDecision::Abstain => {
                "evidence or estimated advantage is below the correction threshold".to_string()
            }
            CorrectionDecision::KeepObserved => unreachable!("handled above"),
        };
        Ok(Correction {
            observed_action: observed_action.to_string(),
            recommended_action: recommendation.selected.action,
            decision,
            advantage_gap,
            confidence,
            reason,
        })
    }
}

#[derive(Debug, Default)]
struct ActionAccumulator {
    weighted_return: f32,
    weight: f32,
    support_count: usize,
    similarity_sum: f32,
}

fn compare_action_scores(left: &ActionScore, right: &ActionScore) -> Ordering {
    right
        .advantage
        .partial_cmp(&left.advantage)
        .unwrap_or(Ordering::Equal)
        .then_with(|| {
            right
                .expected_return
                .partial_cmp(&left.expected_return)
                .unwrap_or(Ordering::Equal)
        })
        .then_with(|| left.action.cmp(&right.action))
}

fn validate_trajectory(transitions: &[Transition]) -> Result<(), StoreError> {
    let dimension = transitions
        .first()
        .ok_or(StoreError::EmptyTrajectory)?
        .state
        .len();
    for transition in transitions {
        validate_state(&transition.state)?;
        if transition.state.len() != dimension {
            return Err(StoreError::StateDimensionMismatch {
                expected: dimension,
                found: transition.state.len(),
            });
        }
        if transition.action.trim().is_empty() {
            return Err(StoreError::EmptyAction);
        }
        if !transition.reward.is_finite() {
            return Err(StoreError::NonFiniteReward);
        }
    }
    Ok(())
}

fn validate_state(state: &[f32]) -> Result<(), StoreError> {
    if state.is_empty() {
        return Err(StoreError::EmptyState);
    }
    if state.iter().any(|value| !value.is_finite()) {
        return Err(StoreError::NonFiniteState);
    }
    Ok(())
}

fn validate_query(query: &[f32]) -> Result<(), SearchError> {
    if query.is_empty() {
        return Err(SearchError::EmptyQuery);
    }
    if query.iter().any(|value| !value.is_finite()) {
        return Err(SearchError::NonFiniteQuery);
    }
    Ok(())
}

fn cosine_similarity(left: &[f32], right: &[f32]) -> f32 {
    let mut dot = 0.0;
    let mut left_norm = 0.0;
    let mut right_norm = 0.0;
    for (&left_value, &right_value) in left.iter().zip(right) {
        dot += left_value * right_value;
        left_norm += left_value * left_value;
        right_norm += right_value * right_value;
    }
    if left_norm == 0.0 || right_norm == 0.0 {
        return 0.0;
    }
    (dot / (left_norm.sqrt() * right_norm.sqrt())).clamp(-1.0, 1.0)
}

#[derive(Debug, Error, PartialEq)]
pub enum StoreError {
    #[error("trajectory store capacity must be positive")]
    InvalidCapacity,
    #[error("trajectory must contain at least one transition")]
    EmptyTrajectory,
    #[error("transition state must contain at least one value")]
    EmptyState,
    #[error("transition state contains a non-finite value")]
    NonFiniteState,
    #[error("transition reward must be finite")]
    NonFiniteReward,
    #[error("transition action must not be empty")]
    EmptyAction,
    #[error("state dimension mismatch: expected {expected}, found {found}")]
    StateDimensionMismatch { expected: usize, found: usize },
}

#[derive(Debug, Error, PartialEq)]
pub enum SearchError {
    #[error("search query must contain at least one value")]
    EmptyQuery,
    #[error("search query contains a non-finite value")]
    NonFiniteQuery,
    #[error("similarity threshold must be in [0, 1]")]
    InvalidSimilarityThreshold,
    #[error("state dimension mismatch: expected {expected}, found {found}")]
    StateDimensionMismatch { expected: usize, found: usize },
}

#[derive(Debug, Error, PartialEq)]
pub enum ReturnError {
    #[error("cannot compute a return for an empty trajectory")]
    EmptyTrajectory,
    #[error("discount factor gamma must be finite and in [0, 1]")]
    InvalidGamma,
    #[error("reward at transition {index} is not finite")]
    NonFiniteReward { index: usize },
    #[error("discounted return at transition {index} is not finite")]
    NonFiniteReturn { index: usize },
}

#[derive(Debug, Error, PartialEq)]
pub enum EngineError {
    #[error(transparent)]
    Store(#[from] StoreError),
    #[error(transparent)]
    Search(#[from] SearchError),
    #[error(transparent)]
    Returns(#[from] ReturnError),
    #[error("gamma must be finite and in [0, 1]")]
    InvalidGamma,
    #[error("top_k must be positive")]
    InvalidTopK,
    #[error("similarity threshold must be in [0, 1]")]
    InvalidSimilarityThreshold,
    #[error("advantage scale must be finite and non-negative")]
    InvalidAdvantageScale,
    #[error("correction thresholds are invalid")]
    InvalidCorrectionThreshold,
    #[error("no similar historical transition was found")]
    NoEvidence,
    #[error("no allowed action has historical evidence")]
    NoAllowedAction,
    #[error("stored trajectory disappeared during scoring")]
    MissingTrajectory,
    #[error("stored transition disappeared during scoring")]
    MissingTransition,
    #[error("observed action must not be empty")]
    EmptyObservedAction,
    #[error("action candidate {index} is empty or has a non-finite base logit")]
    InvalidCandidate { index: usize },
}

fn validate_candidates(candidates: &[ActionCandidate]) -> Result<(), EngineError> {
    if candidates.is_empty() {
        return Err(EngineError::NoEvidence);
    }
    let mut seen = std::collections::BTreeSet::new();
    for (index, candidate) in candidates.iter().enumerate() {
        if candidate.action.trim().is_empty()
            || !candidate.base_logit.is_finite()
            || !seen.insert(candidate.action.as_str())
        {
            return Err(EngineError::InvalidCandidate { index });
        }
    }
    Ok(())
}

fn compare_adjusted_actions(left: &AdjustedAction, right: &AdjustedAction) -> Ordering {
    right
        .adjusted_logit
        .partial_cmp(&left.adjusted_logit)
        .unwrap_or(Ordering::Equal)
        .then_with(|| left.action.cmp(&right.action))
}

